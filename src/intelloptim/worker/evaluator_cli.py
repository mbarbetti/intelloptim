"""Convenience evaluator loop for ``intelloptim-worker evaluator``.

Imports an objective callable from a user module, resolves (or joins) the
matching study on the server, then runs ``study.optimize()`` in a loop.
Designed to be submitted as a SLURM array job so N workers collaborate on
one study without any custom Python wrapper.

Typical invocation (from the sbatch template or directly)::

    intelloptim-worker evaluator \\
        --server https://intelloptim.local \\
        --import my_pkg.objectives:my_fn \\
        --n-trials 50

If the objective was registered with a ``study_spec`` dict via
``@intopt.objective("name", study_spec={...})``, the CLI reads it directly.
Otherwise pass ``--spec-file`` pointing to a JSON file with the
``StudyResolveRequest`` payload (generated by the driver / submit script).
"""

from __future__ import annotations

import json
import sys
from typing import Any, Callable, Dict, Optional, cast

from intelloptim._internal.logging import get_logger

_log = get_logger(__name__)


def _load_spec(
    spec_file: Optional[str],
    import_spec: str,
) -> Dict[str, Any]:
    """Return the study spec dict from *spec_file* or objective metadata."""
    if spec_file is not None:
        with open(spec_file) as fh:
            return cast(Dict[str, Any], json.load(fh))

    # Try objective-attached spec (registered via study_spec= kwarg).
    module_path, _, attr_name = import_spec.partition(":")
    obj_name = attr_name  # treat attr name as registered objective name
    from intelloptim.core.objective import get_study_spec

    spec = get_study_spec(obj_name)
    if spec is not None:
        return spec

    raise RuntimeError(
        f"No study spec available for objective {obj_name!r}. "
        "Either decorate it with study_spec={{...}} in @intopt.objective, "
        "or pass --spec-file <path/to/spec.json>."
    )


def _health_probe(base_url: str, token: str) -> None:
    """GET /healthz and fail fast with a clear message if unreachable."""
    import httpx

    url = base_url.rstrip("/") + "/healthz"
    try:
        resp = httpx.get(url, headers={"Authorization": f"Bearer {token}"}, timeout=10)
        resp.raise_for_status()
    except httpx.TransportError as exc:
        _log.error(
            "server health probe failed — is the server running?",
            extra={"url": url, "error": str(exc)},
        )
        sys.exit(1)
    except httpx.HTTPStatusError as exc:
        _log.error(
            "server health probe returned an error",
            extra={"url": url, "status": exc.response.status_code},
        )
        sys.exit(1)
    _log.info("server health probe passed", extra={"url": url})


def run_evaluator(
    server: str,
    import_spec: str,
    *,
    token: Optional[str] = None,
    spec_file: Optional[str] = None,
    n_trials: int = 50,
    wid: Optional[str] = None,
    site: Optional[str] = None,
    loglevel: str = "INFO",
    catch_exceptions: bool = True,
) -> None:
    """Run the evaluator loop.

    Args:
        server: Base URL of the intelloptim server.
        import_spec: ``"module.path:callable_name"`` string identifying the
            objective.
        token: API bearer token. Falls back to ``INTELLOPTIM_TOKEN`` /
            ``~/.config/intelloptim/token``.
        spec_file: Path to a JSON file containing the ``StudyResolveRequest``
            payload. If ``None``, the spec is read from the objective's
            ``study_spec`` decorator kwarg.
        n_trials: Number of trials this process should contribute.
        wid: Worker ID injected as ``X-Worker-Id`` HTTP header. Auto-derived
            from SLURM env vars if ``None``.
        loglevel: Logging level string.
        catch_exceptions: Whether ``study.optimize()`` should catch and log
            exceptions rather than re-raising (default ``True``).
    """
    from intelloptim._internal.logging import configure_logging
    from intelloptim._internal.schemas import StudyResolveRequest
    from intelloptim.client.auth import resolve_token
    from intelloptim.worker.registry import import_callable
    from intelloptim.worker.slurm import site_id as _auto_site_id
    from intelloptim.worker.slurm import worker_id as _auto_worker_id

    configure_logging(level=loglevel)

    resolved_token = resolve_token(token)
    effective_wid = wid or _auto_worker_id()
    effective_site = site or _auto_site_id()

    _log.info(
        "evaluator starting",
        extra={
            "server": server,
            "import_spec": import_spec,
            "worker_id": effective_wid,
        },
    )

    # 1. Import the objective (triggers @intopt.objective registration).
    objective_fn: Callable[..., Any] = import_callable(import_spec)

    # 2. Health probe — fail fast before doing any real work.
    _health_probe(server, resolved_token)

    # 3. Load study spec and create/join the study.
    spec_dict = _load_spec(spec_file, import_spec)
    spec = StudyResolveRequest.model_validate(spec_dict)

    import httpx

    from intelloptim.client.api import Client

    http_client = httpx.Client(
        base_url=server,
        headers={"X-Worker-Id": effective_wid, "X-Site": effective_site},
        timeout=httpx.Timeout(connect=5.0, read=60.0, write=10.0, pool=5.0),
    )
    with Client(url=server, token=resolved_token, http_client=http_client) as client:
        study = client.create_study(
            name=spec.name,
            direction=spec.direction,
            sampler=spec.sampler,
            parameters=list(spec.parameters),
            pruner=spec.pruner,
        )
        _log.info(
            "study resolved",
            extra={
                "study_id": study.id,
                "existed": study.existed,
                "worker_id": effective_wid,
            },
        )

        # 4. Run the optimize loop.
        catch: Any = Exception if catch_exceptions else None
        study.optimize(objective_fn, n_trials=n_trials, catch=catch)

        best = study.best_trial
        if best is not None:
            _log.info(
                "evaluate done",
                extra={
                    "best_trial": best.number,
                    "best_value": best.value,
                    "worker_id": effective_wid,
                },
            )
        else:
            _log.info(
                "evaluate done — no completed trials yet",
                extra={"worker_id": effective_wid},
            )


__all__ = ["run_evaluator"]
